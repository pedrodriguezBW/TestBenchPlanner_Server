ALTER TABLE proyecto ADD COLUMN numero_proyecto text;
UPDATE proyecto
SET numero_proyecto = substring(titulo FROM '^[[:space:]]*([0-9]+)[[:space:]]*-[[:space:]]');
CREATE FUNCTION proyecto_numero_inicial() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.numero_proyecto := coalesce(NEW.numero_proyecto,
        substring(NEW.titulo FROM '^[[:space:]]*([0-9]+)[[:space:]]*-[[:space:]]'));
    RETURN NEW;
END;
$$;
CREATE TRIGGER proyecto_numero_inicial BEFORE INSERT ON proyecto
    FOR EACH ROW EXECUTE FUNCTION proyecto_numero_inicial();

CREATE TABLE timing_perfil (
    email text NOT NULL REFERENCES usuario(email) ON DELETE CASCADE,
    perfil text NOT NULL CHECK (perfil IN ('solicitante', 'tecnico', 'coordinador')),
    PRIMARY KEY (email, perfil)
);

CREATE TABLE timing_equipo (
    clase text NOT NULL CHECK (clase IN ('banco', 'camara')),
    nombre text NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    version integer NOT NULL DEFAULT 1,
    PRIMARY KEY (clase, nombre)
);
CREATE UNIQUE INDEX timing_equipo_nombre_ci ON timing_equipo (clase, lower(nombre));
INSERT INTO timing_equipo (clase, nombre) VALUES ('banco', 'Cámara Climática');

CREATE TABLE timing_tarea (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origen_id bigint UNIQUE,
    codigo text NOT NULL,
    version integer NOT NULL DEFAULT 1,
    version_importada integer,
    datos jsonb NOT NULL
);
CREATE INDEX timing_tarea_responsable ON timing_tarea ((datos->>'responsable'));
CREATE INDEX timing_tarea_tecnico ON timing_tarea ((datos->>'tecnico'));

CREATE TABLE timing_avance (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarea bigint NOT NULL REFERENCES timing_tarea(id) ON DELETE CASCADE,
    autor text NOT NULL,
    fecha date NOT NULL,
    horas numeric NOT NULL CHECK (horas > 0),
    pendientes numeric CHECK (pendientes >= 0),
    comentario text NOT NULL
);
CREATE INDEX timing_avance_tarea ON timing_avance (tarea, id);

CREATE TABLE timing_historial (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarea bigint NOT NULL REFERENCES timing_tarea(id) ON DELETE CASCADE,
    fecha timestamptz NOT NULL DEFAULT now(),
    autor text NOT NULL,
    accion text NOT NULL,
    datos jsonb NOT NULL
);
CREATE INDEX timing_historial_tarea ON timing_historial (tarea, id);

REVOKE ALL ON timing_perfil, timing_equipo, timing_tarea, timing_avance, timing_historial FROM tbp_consulta;
